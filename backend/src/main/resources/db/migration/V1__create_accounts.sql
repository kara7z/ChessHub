CREATE TABLE accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(64) NOT NULL,
    email varchar(254) NOT NULL,
    password_hash varchar(255) NOT NULL,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    role varchar(16) NOT NULL DEFAULT 'PLAYER',
    status varchar(16) NOT NULL DEFAULT 'PENDING',
    email_verified_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT accounts_role_check CHECK (role IN ('ADMIN', 'PLAYER')),
    CONSTRAINT accounts_status_check CHECK (status IN ('PENDING', 'ACTIVE', 'REJECTED', 'SUSPENDED'))
);

CREATE UNIQUE INDEX accounts_email_unique ON accounts (lower(email));
CREATE UNIQUE INDEX accounts_username_unique ON accounts (lower(username));
